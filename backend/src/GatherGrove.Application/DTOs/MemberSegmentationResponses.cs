namespace GatherGrove.Application.DTOs;

/// <summary>
/// Response for member segment operations
/// </summary>
public class MemberSegmentResponse
{
    /// <summary>
    /// Unique identifier for the segment
    /// </summary>
    public int Id { get; set; }

    /// <summary>
    /// Club this segment belongs to
    /// </summary>
    public int ClubId { get; set; }

    /// <summary>
    /// Name of the segment
    /// </summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>
    /// Description of the segment
    /// </summary>
    public string? Description { get; set; }

    /// <summary>
    /// Filter criteria as a structured object
    /// </summary>
    public SegmentFilterCriteria FilterCriteria { get; set; } = new();

    /// <summary>
    /// Raw filter criteria JSON for storage
    /// </summary>
    public string FilterCriteriaJson { get; set; } = string.Empty;

    /// <summary>
    /// Whether the segment is active
    /// </summary>
    public bool IsActive { get; set; }

    /// <summary>
    /// Whether this segment was generated by the system
    /// </summary>
    public bool IsSystemGenerated { get; set; }

    /// <summary>
    /// Current count of members in this segment
    /// </summary>
    public int MemberCount { get; set; }

    /// <summary>
    /// When the segment was last calculated
    /// </summary>
    public DateTime? LastCalculated { get; set; }

    /// <summary>
    /// Duration of last calculation in milliseconds
    /// </summary>
    public int? CalculationDurationMs { get; set; }

    /// <summary>
    /// When the segment was created
    /// </summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>
    /// User who created the segment
    /// </summary>
    public string CreatedByUserName { get; set; } = string.Empty;

    /// <summary>
    /// When the segment was last updated
    /// </summary>
    public DateTime UpdatedAt { get; set; }

    /// <summary>
    /// Performance metrics for this segment (if requested)
    /// </summary>
    public SegmentPerformanceMetrics? PerformanceMetrics { get; set; }
}

/// <summary>
/// Response for segment calculation operations
/// </summary>
public class SegmentCalculationResult
{
    /// <summary>
    /// ID of the segment that was calculated
    /// </summary>
    public int SegmentId { get; set; }

    /// <summary>
    /// Number of members in the segment after calculation
    /// </summary>
    public int MemberCount { get; set; }

    /// <summary>
    /// Duration of the calculation in milliseconds
    /// </summary>
    public int CalculationDurationMs { get; set; }

    /// <summary>
    /// When the calculation was performed
    /// </summary>
    public DateTime CalculatedAt { get; set; }

    /// <summary>
    /// Whether the segment cache was updated
    /// </summary>
    public bool CacheUpdated { get; set; }

    /// <summary>
    /// Changes in member count since last calculation
    /// </summary>
    public int MemberCountChange { get; set; }

    /// <summary>
    /// List of members added to the segment
    /// </summary>
    public List<SegmentMemberChange> MembersAdded { get; set; } = new();

    /// <summary>
    /// List of members removed from the segment
    /// </summary>
    public List<SegmentMemberChange> MembersRemoved { get; set; } = new();
}

/// <summary>
/// Response for getting segment members
/// </summary>
public class SegmentMembersResult
{
    /// <summary>
    /// Total number of members in the segment
    /// </summary>
    public int TotalCount { get; set; }

    /// <summary>
    /// Current page number
    /// </summary>
    public int CurrentPage { get; set; }

    /// <summary>
    /// Number of results per page
    /// </summary>
    public int PageSize { get; set; }

    /// <summary>
    /// Total number of pages
    /// </summary>
    public int TotalPages => (int)Math.Ceiling((double)TotalCount / PageSize);

    /// <summary>
    /// List of members in the segment
    /// </summary>
    public List<SegmentMemberDetail> Members { get; set; } = new();

    /// <summary>
    /// When the segment was last calculated
    /// </summary>
    public DateTime? LastCalculated { get; set; }

    /// <summary>
    /// Whether the cache is up to date
    /// </summary>
    public bool CacheIsValid { get; set; }
}

/// <summary>
/// Detailed member information for segment results
