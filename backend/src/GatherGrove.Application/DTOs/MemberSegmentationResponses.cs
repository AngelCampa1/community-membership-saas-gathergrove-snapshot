}

/// <summary>
/// Member engagement data for segment results
/// </summary>
public class MemberEngagementData
{
    /// <summary>
    /// Overall engagement score
    /// </summary>
    public decimal OverallScore { get; set; }

    /// <summary>
    /// Engagement level (1=High, 2=Moderate, 3=At Risk)
    /// </summary>
    public int Level { get; set; }

    /// <summary>
    /// Visual indicator color
    /// </summary>
    public string VisualIndicator { get; set; } = string.Empty;

    /// <summary>
    /// Individual score components
    /// </summary>
    public EngagementScoreComponents ScoreComponents { get; set; } = new();
}

/// <summary>
/// Individual engagement score components
/// </summary>
public class EngagementScoreComponents
{
    public decimal LoginFrequencyScore { get; set; }
    public decimal EventParticipationScore { get; set; }
    public decimal CommunicationScore { get; set; }
    public decimal FeatureUsageScore { get; set; }
    public decimal ProfileCompletenessScore { get; set; }
}

/// <summary>
