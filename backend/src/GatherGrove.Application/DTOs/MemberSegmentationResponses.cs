    /// </summary>
    public int EstimatedMemberCount { get; set; }

    /// <summary>
    /// Estimated execution time in milliseconds
    /// </summary>
    public int EstimatedExecutionTimeMs { get; set; }

    /// <summary>
    /// Performance impact level
    /// </summary>
    public PerformanceImpact PerformanceImpact { get; set; }
}

/// <summary>
