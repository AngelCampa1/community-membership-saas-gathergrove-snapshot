// ─────────────────────────────────────────────────────────────────────────────
// Patch globals.css with generated token vars (between markers)
// ─────────────────────────────────────────────────────────────────────────────

const GLOBALS_BEGIN ='/* ── BEGIN AUTO-GENERATED TOKENS (shared/design-tokens/build.mjs) ── */';
const GLOBALS_END   ='/* ── END AUTO-GENERATED TOKENS ── */';

async function patchGlobalsCss(cssVarBlock) {
  const globalsPath = path.join(ROOT,'client/src/app/globals.css');
  const original = await readFile(globalsPath,'utf-8');

  // Strip the generated comment header from the standalone tokens.css content
  // (globals.css gets the same :root/.light content, but wrapped in markers)
  const varContent = cssVarBlock
    .replace(/^\/\*.*?\*\/\n\/\*.*?\*\/\n\n/s,'')  // remove 2-line auto-gen header
    .trimEnd();

  const patchedBlock = `${GLOBALS_BEGIN}\n${varContent}\n${GLOBALS_END}`;

  let updated;
  if (original.includes(GLOBALS_BEGIN) && original.includes(GLOBALS_END)) {
    // Replace existing markers
    const beginIdx = original.indexOf(GLOBALS_BEGIN);
    const endIdx = original.indexOf(GLOBALS_END) + GLOBALS_END.length;
    updated = original.slice(0, beginIdx) + patchedBlock + original.slice(endIdx);
  } else {
    // Insert after the last closing brace of the dev-overlay block
    // (before `@layer base`)
    const insertBefore ='\n@layer base {';
    const idx = original.indexOf(insertBefore);
    if (idx === -1) {
      console.warn('  ⚠ Could not find @layer base in globals.css — skipping patch');
      return;
    }
    updated = original.slice(0, idx) +'\n' + patchedBlock +'\n' + original.slice(idx);
  }

  await writeFile(globalsPath, updated,'utf-8');
  console.log(`  ✓ client/src/app/globals.css (patched token vars)`);
}

async function main() {
  console.log('🎨 Building design tokens...\n');

  const tokens = await loadTokens();
  const cssContent = buildCss(tokens);

  const outputs = [
    {
      path: path.join(ROOT,'client/src/generated/tokens.css'),
      content: cssContent,
      label:'CSS (web)',
    },
    {
      path: path.join(ROOT,'client/src/generated/tokens.ts'),
      content: buildTsWeb(tokens),
      label:'TypeScript (web)',
    },
    {
      path: path.join(ROOT,'mobile/src/generated/tokens.ts'),
      content: buildTsMobile(tokens),
      label:'TypeScript (mobile)',
    },
    {
      path: path.join(ROOT,'backend/src/GatherGrove.Application/Generated/DesignTokens.cs'),
      content: buildCSharp(tokens),
      label:'C# (backend)',
    },
  ];

  for (const { path: filepath, content } of outputs) {
    await writeOutput(filepath, content);
  }

  // Patch globals.css with the generated :root/.light vars
  await patchGlobalsCss(cssContent);

  console.log('\n✅ All token files generated successfully.');
}

main().catch((err) => {
  console.error('❌ Token build failed:', err);
  process.exit(1);
});
